package SUS;

public class Imposter3 {
	public static void main(String[] args) {
	
		int [][] arr = {{1,2},{3,4}};
		
		System.out.print("The array Elements: "+"\n");
		for(int i = 0; i < 2 ; i++) {
			for(int j = 0; j < 2 ; j++) {
				System.out.print(arr[i][j] + "\t");
				}
			System.out.print('\n');
			}
	}
}
